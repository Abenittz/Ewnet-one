from datetime import datetime
import uuid
from pydantic import BaseModel, ConfigDict, EmailStr, Field


class UserBase(BaseModel):
    email: EmailStr
    display_name: str | None = None


class UserCreate(UserBase):
    password: str = Field(min_length=6, description="Password must be at least 6 characters long")
    device_name: str | None = Field(default=None, description="Client or mobile device name, e.g. iPhone Safari PWA")
    guest_user_id: uuid.UUID | None = Field(default=None, description="Optional guest user ID to migrate bookmarks and progress from")


class UserLogin(BaseModel):
    email: EmailStr
    password: str
    device_name: str | None = Field(default=None, description="Client or mobile device name, e.g. Android Chrome PWA")


class UserUpdate(BaseModel):
    display_name: str | None = None
    password: str | None = Field(default=None, min_length=6)


class UserResponse(UserBase):
    id: uuid.UUID
    is_active: bool
    is_superuser: bool
    is_guest: bool = False
    created_at: datetime
    updated_at: datetime

    model_config = ConfigDict(from_attributes=True)


class Token(BaseModel):
    access_token: str
    refresh_token: str
    token_type: str = "bearer"
    expires_in: int = Field(default=3600, description="Access token expiration lifespan in seconds")
    user: UserResponse


class RefreshTokenRequest(BaseModel):
    refresh_token: str = Field(..., description="Active refresh token to rotate")
    device_name: str | None = Field(default=None, description="Optional updated device name")


class GuestAuthRequest(BaseModel):
    device_name: str | None = Field(default=None, description="Client or mobile device name, e.g. iPhone 15 PWA")
    client_id: uuid.UUID | None = Field(default=None, description="Optional persistent client device UUID generated by frontend")


class UpgradeGuestRequest(BaseModel):
    email: EmailStr
    password: str = Field(min_length=6, description="Password must be at least 6 characters long")
    display_name: str | None = None


class LogoutRequest(BaseModel):
    refresh_token: str | None = Field(default=None, description="Refresh token to revoke")


class SessionResponse(BaseModel):
    id: uuid.UUID
    device_name: str | None
    created_at: datetime
    expires_at: datetime
    is_current: bool = False

    model_config = ConfigDict(from_attributes=True)

